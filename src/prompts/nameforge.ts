/**
 * 取名域：按类别批量生成中文网文专有名字（人名 / 地名 / 功法 / 势力 / 宝物）。
 *
 * 本文件同时是提示词注册表的域模块之一（见 catalog.ts）。
 *
 * 设计边界：
 *   * 取名是**辅助资产**，产出进「名字库」供作者采纳；采纳后的名字才注入
 *     写作提示词（书名库渲染在 prompts/writing.ts 的本书层）；
 *   * 提示词只描述「怎么取名」，不写死任何名字——所有候选来自模型按本书
 *     语境（题材 / 世界设定 / 已有名字避重）的实时生成。
 */

import type { PromptEntry } from './catalog.ts'

/** 取名系统提示词：类别感知 + 避重 + 结构化 JSON 输出。 */
export function nameForgeSystemPrompt(): string {
  return [
    '你是资深中文网文命名师，擅长按题材气质取「读一遍就记得住」的专有名字。',
    '硬规则：',
    '1. 只输出 JSON 对象，格式 {"names":[{"name":"名字","note":"命名理由/意象（20字内）"}]}，不要输出其他文字；',
    '2. 名字必须是中文（人名2-4字、地名2-6字、功法3-7字、势力2-8字、宝物2-8字），不得出现外文、拼音、生僻怪字；',
    '3. 严格避雷：不得使用真实存在的明星、品牌、企业、敏感人物名；不套用其它作品的成名专名；',
    '4. 每批名字内部不得互相近音、近形；若给出「避用名单」，其中名字一个都不得再产出；',
    '5. note 只写命名思路（取自什么意象/气质），不复述名字本身。',
  ].join('\n')
}

/** 本域提示词登记（注册表消费）。 */
export const entries: PromptEntry[] = [
  { id: 'nameforge.generate', description: '取名：按类别批量生成专有名字（题材感知 + 避重 + 理由）' },
]
