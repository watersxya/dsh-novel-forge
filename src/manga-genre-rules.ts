/** 通用题材（空规则，走通用生成）。 */
export const DEFAULT_GENRE: GenreRule = { id: 'default', label: '通用（不限定）', rules: [] }

/** 按题材 id 取规则（未找到返回通用）。 */
export function getGenreRules(id?: string): string[] {
  if (id === undefined || id === '') return DEFAULT_GENRE.rules
  const g = GENRES.find(x => x.id === id)
  return g !== undefined ? g.rules : DEFAULT_GENRE.rules
}

/** 取题材 label（展示用）。 */
export function getGenreLabel(id?: string): string {
  if (id === undefined || id === '') return DEFAULT_GENRE.label
  const g = GENRES.find(x => x.id === id)
  return g !== undefined ? g.label : id
}
